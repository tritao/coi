#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class Event:
    kind: str
    args: list[int]


def parse_script(text: str) -> dict[int, list[Event]]:
    events: dict[int, list[Event]] = {}
    frame = 0
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        cmd = parts[0]
        if cmd == "wait" or cmd == "frames":
            if len(parts) != 2:
                raise ValueError(f"invalid {cmd}: {raw}")
            frame += int(parts[1])
            continue
        if cmd in ("click", "pointer"):
            if len(parts) != 3:
                raise ValueError(f"invalid {cmd}: {raw}")
            x = int(float(parts[1]))
            y = int(float(parts[2]))
            events.setdefault(frame, []).append(Event(cmd, [x, y]))
            continue
        if cmd == "scroll":
            if len(parts) != 3:
                raise ValueError(f"invalid {cmd}: {raw}")
            dx = int(float(parts[1]))
            dy = int(float(parts[2]))
            events.setdefault(frame, []).append(Event(cmd, [dx, dy]))
            continue
        if cmd == "snapshot":
            events.setdefault(frame, []).append(Event(cmd, []))
            continue
        raise ValueError(f"unknown command: {cmd} ({raw})")
    return events


