def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--script", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    text = args.script.read_text(encoding="utf-8")
    events = parse_script(text)
    max_frame = max(events.keys(), default=0)
    if "wait" in text or "frames" in text:
        # Conservative: if script advances frames via waits, max_frame is already final frame.
        pass

    # Convert to JSON-friendly dict
    out_events: dict[str, list[list[object]]] = {}
    for f, evs in events.items():
        out_events[str(f)] = [[e.kind, e.args] for e in evs if e.kind != "snapshot"]

    js = WEB_VISUAL_JS.replace("__COI_VISUAL_EVENTS__", json.dumps(out_events, separators=(",", ":")))
    js = js.replace("__COI_VISUAL_MAX_FRAME__", str(max_frame))

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(js, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
